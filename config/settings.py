"""Configuración de Django para el proyecto MiniConf.

Los valores sensibles (clave secreta, modo debug, hosts y base de datos)
se leen de variables de entorno o de un archivo .env que no se sube a Git.
Ver .env.example.
"""

import os
from pathlib import Path

from django.core.exceptions import ImproperlyConfigured
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent.parent

